#include "PPPheaders.h"

int main() {
	cout << "Recipe" << endl;
	cout << "1. Preheat over to 400 degrees F. Grease a 12 cup muffin tin or use cups with paper liners." << endl;
	cout << "2. Stir 2 cups of all-purpose flour, 3 teaspoons of baking powder, 1/2 teaspoon of salt, and 3/4 cup of white sugar in a bowl together. Make a well in the center." << endl;
	cout << "3. Beat 1 egg with a fork in a small bowl. Whisk in 1 cup of milk and 1/4 cup vegetable oil into bowl." << endl;
	cout << "4. Pour in liquid mixture into flour mixture. Mix quickly and lightly with a fork until just moistened (the batter will be lumpy). Spoon batter into muffin cups, filling batter to 3/4 of each cup." << endl;
	cout << "5. Bake in the preheated over until tops spring back when lightly pressed. This will take about 25 minutes." << endl;
	cout << endl << "Glossary" << endl;
	cout << "Preheating: to set the oven to a certain temperature before starting the baking process." << endl;
	cout << "Oven: An appliance used to bake goods." << endl;
	cout << "Muffin tin: A place used to pour muffin batter into when baking." << endl;

	return 0;
}
